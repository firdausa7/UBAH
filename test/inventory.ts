// "GET /staff/cases/:id" -> matches "/staff/cases/12"
export function routeExists(method: string, path: string): boolean {
  // Express matches "/staff" and "/staff/" alike (non-strict routing).
  const clean = path.split("?")[0].split("#")[0].replace(/\/$/, "") || "/";
  return INVENTORY.some((r) => {
    const [m, p] = r.split(" ");
    if (m !== method.toUpperCase()) return false;
    const re = new RegExp(`^${p.replace(/\/$/, "").replace(/[.*+?^${}()|[\]\\]/g, "\\$&").replace(/:[a-zA-Z]+/g, "[^/]+")}/?$`);
    return re.test(clean);
  });
}
